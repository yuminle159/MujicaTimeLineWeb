"""Validate venue coverage against Excel and build the browser catalogue.

Usage: python sync_venues.py [--check] [--build-map]
The live history itself is joined in the browser, so normal Live updates need
no second history export and no executable rebuild.
"""
import argparse
import json
import math
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def normalize(value):
    return re.sub(r'\s+', '', unicodedata.normalize('NFKC', str(value or ''))).lower()


def validate(catalogue, names):
    aliases, ids = {}, set()
    for venue in catalogue['venues']:
        assert venue['id'] not in ids, f"Duplicate ID: {venue['id']}"
        ids.add(venue['id'])
        for name in [venue['name'], *venue.get('aliases', [])]:
            key = normalize(name)
            assert key not in aliases or aliases[key] == venue['id'], f'Duplicate alias: {name}'
            aliases[key] = venue['id']
        assert venue['region'] in ('jp', 'overseas', 'unknown')
        if venue['region'] == 'jp':
            assert 122 <= venue['lon'] <= 154 and 20 <= venue['lat'] <= 46
        if venue.get('capacity'):
            assert venue.get('capacity_source'), f"Missing capacity source: {venue['name']}"
    return sorted({name for name in names if normalize(name) not in aliases})


def simplify(points, tolerance=0.006):
    if len(points) < 3:
        return points
    a, b = points[0], points[-1]
    dx, dy = b[0]-a[0], b[1]-a[1]
    denom = dx*dx + dy*dy
    def distance(p):
        t = max(0, min(1, ((p[0]-a[0])*dx+(p[1]-a[1])*dy)/denom)) if denom else 0
        return math.hypot(p[0]-a[0]-t*dx, p[1]-a[1]-t*dy)
    index = max(range(1, len(points)-1), key=lambda i: distance(points[i]))
    if distance(points[index]) <= tolerance:
        return [a, b]
    return simplify(points[:index+1], tolerance)[:-1] + simplify(points[index:], tolerance)


def omit_disputed_polygon(prefecture_id, polygon):
    """Omit disputed island groups from this venue map, before simplification.

    Test whole-island bounding boxes so Hokkaido's mainland is never clipped.
    The rule applies equally to the main map and its locator thumbnail.
    """
    west = min(p[0] for p in polygon[0])
    south = min(p[1] for p in polygon[0])
    east = max(p[0] for p in polygon[0])
    north = max(p[1] for p in polygon[0])
    if prefecture_id == 1:
        return west >= 145.4 and south >= 43.35
    if prefecture_id == 47:
        return west >= 123.4 and east <= 124.7 and south >= 25.7 and north <= 26.1
    if prefecture_id == 32:
        return west >= 131.8 and east <= 132 and south >= 37.1 and north <= 37.4
    return False


def build_map(source=None):
    source = Path(source) if source else ROOT/'_data/venue-map-outline.json'
    islands = json.loads(source.read_text(encoding='utf-8'))['islands']
    assert len(islands) == 4 and {v['name'] for v in islands} == {'本州', '北海道', '九州', '四国'}, 'Use the four-island schematic source only'
    result = []
    for island in islands:
        ring = island['ring']
        assert len(ring) >= 4 and ring[0] == ring[-1], 'Expected a closed island outline'
        path = 'M' + 'L'.join(f'{x*80.9:.2f},{-y*100:.2f}' for x,y in ring) + 'Z'
        result.append({'name': island['name'], 'path': path})
    (ROOT/'js/venue-atlas-map.js').write_text(
        '// Four-island schematic from _data/venue-map-outline.json; derived from GSI / dataofjapan.\n'
        'window.VENUE_ATLAS_MAP = ' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--build-map', action='store_true', help='Build the four-island schematic')
    parser.add_argument('--map-source', help='Alternative four-island outline JSON (not raw GeoJSON)')
    args = parser.parse_args()
    import openpyxl
    catalogue = json.loads((ROOT/'_data/venues.json').read_text(encoding='utf-8'))
    wb = openpyxl.load_workbook(ROOT/'_data/data.xlsx', read_only=True, data_only=True)
    rows = iter(wb['lives'].values)
    headers = next(rows)
    col = headers.index('live_venue')
    names = [row[col] for row in rows if row[col]]
    wb.close()
    missing = validate(catalogue, names)
    if missing:
        raise SystemExit('Missing venues: ' + ', '.join(missing))
    if not args.check:
        (ROOT/'js/venue-atlas-data.js').write_text(
            '// Generated by sync_venues.py; edit _data/venues.json.\nwindow.VENUE_ATLAS_DATA = ' +
            json.dumps(catalogue, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
        if args.build_map or args.map_source:
            build_map(args.map_source)
    print(f'Venue coverage OK: {len(names)} live records, {len(catalogue["venues"])} catalogue entries.')


if __name__ == '__main__':
    main()
