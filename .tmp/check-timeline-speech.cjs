const fs = require('fs'), vm = require('vm'), assert = require('assert');
const source = fs.readFileSync('timeline/page.js','utf8');
new vm.Script(source);
const start = source.indexOf('  function renderDescription(');
const end = source.indexOf('  const detailNavigation', start);
const ctx = {};
vm.runInNewContext(source.slice(start,end),ctx);
assert(!ctx.renderDescription('佐佐木李子评论区互动').includes('tl-speech'));
const html = ctx.renderDescription('介绍\n高尾奏音：你好<script>\n第二行\n佐佐木李子：谢谢');
assert.equal((html.match(/<article/g)||[]).length,2);
assert(html.includes('事件说明') && html.includes('@Kanon_Takao') && html.includes('@sasakirico'));
assert(html.includes('&lt;script&gt;') && !html.includes('<script>'));
assert(ctx.renderDescription('2024.11.02的佐佐木李子：回忆').includes('2024.11.02 · 译文'));
assert(ctx.renderDescription('李子→奏音：感言').includes('@sasakirico'));
const annotated=ctx.renderDescription('佐佐木李子：约好了\n（原文：約束，就是歌名）');
assert(annotated.indexOf('</blockquote>') < annotated.indexOf('（原文：'));
vm.runInNewContext(fs.readFileSync('timeline/data.js','utf8'),ctx);
const lunch=ctx.timelineData.find(e=>e.hash_id==='8ApdB0SxHfr');
const thread=ctx.renderDescription(lunch.description);
assert.equal((thread.match(/<article/g)||[]).length,3);
assert.equal((thread.match(/has-reply/g)||[]).length,2);
assert.equal((thread.match(/ · 回复/g)||[]).length,2);
assert.equal((thread.match(/tl-translation-note/g)||[]).length,1);
assert(!thread.includes('回复|'));
assert(!lunch.media.some(m=>m.type==='image'));
assert(!ctx.renderDescription('高尾奏音：正文\n佐佐木李子：独立发言').includes('has-reply'));
assert(!ctx.renderDescription('回复|佐佐木李子：单独回复').includes('has-reply'));
const numbered=ctx.renderDescription('佐佐木李子①：第一篇\n佐佐木李子②：第二篇');
assert.equal((numbered.match(/<article/g)||[]).length,2);
assert(!/[①②]/.test(numbered));
assert(!numbered.includes('has-reply'));
const liked=ctx.renderDescription('高尾奏音：主帖\n点赞|佐佐木李子\n高尾奏音：另一篇');
assert.equal((liked.match(/<article/g)||[]).length,2);
assert.equal((liked.match(/class="tl-like"/g)||[]).length,1);
assert(liked.includes('已点赞')&&!liked.includes('点赞|'));
assert(!liked.includes('has-reply'));
assert(ctx.renderDescription('点赞｜高尾奏音：Instagram <记录>').includes('Instagram &lt;记录&gt;'));
assert(!source.includes('has-quote')&&!source.includes('isQuote'));
let speechEvents = 0;
for (const ev of ctx.timelineData) if(ctx.renderDescription(ev.description || '').includes('<article')) speechEvents++;
console.log(`PASS: syntax, escaping, speaker boundaries, dated/arrow labels; ${speechEvents} events rendered with speech bubbles.`);
assert.equal(ctx.interactionImageLabel({type:'image',src:'../images/2026-推特回复.webp'}),'X 回复 · 译图');
assert.equal(ctx.interactionImageLabel({type:'image',src:'../images/2026-ins点赞.webp'}),'Instagram · 点赞记录');
assert.equal(ctx.interactionImageLabel({type:'image',src:'../images/2026-ins.webp'}),'Instagram · 互动记录');
assert.equal(ctx.interactionImageLabel({type:'image',src:'../images/2026-1.webp'}),'');
assert.equal(ctx.interactionImageLabel({type:'video',src:'../images/2026-ins.webp'}),'');
let records=0,events=0,onlyRecords=0;
const path=require('path');
for(const ev of ctx.timelineData){
 const media=ev.media||[], recordsHere=media.filter(ctx.interactionImageLabel);
 if(recordsHere.length){ events++; records+=recordsHere.length; if(!media.some(m=>m.type==='image'&&!ctx.interactionImageLabel(m)))onlyRecords++; }
 for(const item of recordsHere)assert(fs.existsSync(path.resolve('timeline',item.src)),item.src);
}
console.log(`PASS: ${records} interaction images in ${events} events, ${onlyRecords} without ordinary photos; all files exist.`);
